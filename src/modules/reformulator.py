import json
import re
from langchain_openai import ChatOpenAI
from langchain_core.prompts import ChatPromptTemplate


def reformulate_query(query: str, chat_history: list = None) -> dict:
    """
    [기능] 질문을 분석하여 다중 쿼리와 메타데이터 필터 조건을 동시에 추출합니다.
    - 반환 형태: {"queries": ["검색어1"], "filters": {"발주 기관": "한영대학교"}}
    """
    # 1. 대화 기록이 비어있다면 굳이 LLM을 부르지 않고 원본 질문을 그대로 반환 (속도 최적화)
    if chat_history is None:
        chat_history = []
        
    # 2. 모델
    llm = ChatOpenAI(model="gpt-5-mini", temperature=0)
    
    # 3. LLM에게 내릴 명확한 지시사항
    prompt = ChatPromptTemplate.from_messages([
        ("system", """
        너는 RAG 검색 엔진의 질문 분석, 문맥 복원, 검색 질의 정규화, 메타데이터 필터 추출 전문가다.
        사용자의 현재 질문과 대화 기록을 분석하여 검색에 적합한 질의와 필터를 생성하라.

        [작업 목표]
        1. 대화 기록을 참고해 생략된 대상이나 대명사를 복원한다.
        2. 추천/판단/대화형 메타표현이 포함된 질문을 실제 공고문/제안요청서/사업설명에서 검색 가능한 표현으로 정규화한다.
        3. 검색에 유용한 메타데이터 필터(발주기관, 사업명, 금액, 일정 등)를 추출한다.
        4. 비교 질문은 독립된 여러 검색 질의로 분리한다.

        [정규화 원칙]
        - '추천해줘', '알려줘', '찾아줘', '적합한', '회사에 맞는' 같은 메타표현은 제거한다.
        - '경험 있는 업체', '잘하는 업체', '추천 업체', '가능한 업체' 같은 평가/판단 표현은 queries에 직접 넣지 말고, 현재 질문에 근거해 확인 가능한 사업 범위/요구사항/사업유형 표현으로 바꾼다.
        - 질문에 없는 기관명, 사업명, 금액, 일정, 기술, 제품명, 방법론, 약어를 새로 추가하지 않는다.
        - 자격요건, 경력요구, 수행경력, 적합성 판단 표현을 괄호나 수식어 형태로 queries에 덧붙이지 않는다.
        (예: '대학 시스템 구축 공고' O / '대학 시스템 구축 공고(사업수행경력 요구)' X)
        - queries는 업체 소개문이나 평가문이 아니라, 문서 제목이나 본문에 실제로 등장할 법한 일반적 공고형 표현으로 작성한다.
        - 완전한 설명문이 아니라 짧고 검색 가능한 질의 형태로 만든다.
        - 검색 질의는 질문 의미를 유지하되 과도하게 구체화하지 않는다.
        - 대화 기록은 생략된 대상이나 대명사 복원에만 사용하며, 현재 질문에 없는 기관명·사업명·금액·일정·기술어를 새로 구체화하는 근거로 사용하지 않는다.

        [일반 질문 생성 규칙]
        - 일반 질문은 동일한 검색 의도를 공유하는 범위에서 1~4개의 질의를 생성한다.
        - 가능한 경우 가장 일반적이고 포괄적인 질의를 우선 1개 생성한다.
        - 질문이 추상적이거나 범위가 넓고 특정 기관명/사업명/기간/금액이 없으면 recall 확보를 위해 2~3개의 질의를 생성할 수 있다.
        - 보조 질의는 유사 표현 반복이 아니라, 동일한 검색 의도를 유지하는 범위에서 대표 하위 유형 또는 문서 표면형으로 다각화한다.
        - 보조 질의는 질문에 없는 세부 기술어, 기관명, 사업명, 금액, 일정, 방법론을 새로 추가해 구체화하지 않는다.
        (예: '대학 시스템 구축 공고' → '대학 학사정보시스템 구축 공고', '대학 행정정보시스템 구축 공고')

        [비교 질문 생성 규칙]
        - 비교 질문은 비교 대상을 독립 질의로 분리하되, 동일한 비교 축과 검색 의도를 유지한다.
        - 서로 지나치게 다른 방향으로 확장하지 않는다.
        - 기관명만 있고 사업명이 없으면 사업명을 추측하지 말고 '기관명 + 사업 공고' 수준으로 생성한다.
        (예: '경희대학교 사업 공고' O / '경희대학교 학사정보시스템 구축 사업' X)
        - 사업명만 있고 기관명이 없으면 기관명을 추측하지 말고 '사업명' 또는 '사업유형 + 공고' 수준으로 생성한다.
        (예: '차세대 포털 구축 공고' O / '고려대학교 차세대 포털 구축 공고' X)

        [질문 유형별 처리]
        - 금액/조건 → 금액, 자격, 조건이 드러나는 공고 질의
        - 기술/역량 → 해당 기술 또는 업무 범위가 드러나는 사업/요구사항 질의
        - 기관/분야 → 기관명, 분야명, 사업명 중심 공고 질의
        - 마감/일정 → 일정, 기간, 마감일 중심 공고 질의
        - 사업유형 → 질문이나 대화 기록에서 드러난 구축, 운영, 유지보수, 고도화, 이전, 전환, ISP, 컨설팅 등 사업 성격 중심 질의
        - 추천/적합성 판단 질문 → 평가 표현은 제거하고, 판단 근거가 되는 사업 분야·업무 범위·요구사항 중심 질의로 변환

        [필터 추출 규칙]
        - 질문에 특정 발주기관, 사업명, 금액, 일정 등이 명시되어 있으면 filters에 넣는다.
        (예: "N억 이상" → {{"min_budget": N*100000000}} 형태로 추출한다.)
        (예: "N억 이하" → {{"max_budget": N*100000000}} 형태로 추출한다.)
        (예: "N억~M억" → {{"min_budget": N*100000000, "max_budget": M*100000000}} 형태로 추출한다)
        (예: "N월 N일 이전 마감", "N월까지" → {{"deadline_before": "YYYY-MM-DD 00:00:00"}} 형태로 추출한다)
        (예: "N월 N일 이후 마감", "N월부터" → {{"deadline_after": "YYYY-MM-DD 00:00:00"}} 형태로 추출한다)
        - 현재 질문에 명시되지 않은 기관명, 사업명, 금액, 일정은 queries나 filters에 추가하지 않는다.
        - 대화 기록의 기관명, 사업명, 금액, 일정은 현재 질문에서 '그거', '이 사업', '위 공고'처럼 다시 참조하는 경우에만 queries나 filters에 사용할 수 있다.
        - 명시되지 않으면 해당 filters는 비워둔다.

        [출력 규칙]
        - 반드시 아래 JSON 형식으로만 출력한다.
        - 다른 설명은 절대 출력하지 않는다.

        [출력 예시]
        {{
        "queries": ["클라우드 전환 및 정보시스템 이전 관련 구축 또는 고도화 공고"],
        "filters": {{}}
        }}

        [출력 예시 2]
        {{
        "queries": ["한영대학교 학사정보시스템 구축 예산", "한국대학교 차세대 시스템 구축 예산"],
        "filters": {{
            "발주 기관": "한영대학교, 한국대학교",
            "사업명": "학사정보시스템, 차세대 시스템"
        }}
        }}
         
        [출력 예시 3]
        {{
        "queries": ["대규모 정보시스템 구축 사업 공고"],
        "filters": {{
            "min_budget": 500000000
        }}
        }}

        [출력 예시 4]
        {{
        "queries": ["마감일 임박 시스템 구축 공고"],
        "filters": {{
            "deadline_before": "2024-08-31 00:00:00"
        }}
        }}
        """),
        ("human", "[대화 기록]:\n{history}\n\n[현재 질문]: {question}")
    ])
    
    # 4. 딕셔너리 형태의 대화 기록을 LLM이 읽기 편한 문자열로 변환
    history_str = "\n".join([
        f"{'User' if msg.get('role') == 'user' else 'Bot'}: {msg.get('content', '')}"
        for msg in chat_history
    ])

    # 5. 실행 및 무중단 에러 방어
    try:
        chain = prompt | llm
        result = chain.invoke({"history": history_str, "question": query}).content.strip()
        
        # 마크다운 코드블록(```json)이 붙어있을 경우 제거
        result = re.sub(r"```json\n?|```", "", result).strip()
        
        parsed_data = json.loads(result)
        print(f"🔄 [질문 분석 완료] 쿼리: {parsed_data.get('queries', [])} | 필터: {parsed_data.get('filters', {})}")
        return parsed_data
        
    except Exception as e:
        print(f"⚠️ [분석 에러] 기본 검색으로 폴백 (필터 없음): {e}")
        return {"queries": [query], "filters": {}}    
